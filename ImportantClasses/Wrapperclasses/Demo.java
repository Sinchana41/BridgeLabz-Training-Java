package ImportantClasses.Wrapperclasses;

public class Demo {
    //byte - Byte
    //short - Short
    //int - Integer
    //long - Long
    //float - Float
    //double - Double
    //char - Character
    //boolean - Boolean

    public static void main(String[] args) {

        //Auto-boxing - converting from primitive to non-primitive
        int num1 = 5;
        Integer num2 = num1;
        System.out.println(num2);

        //Auto-unboxing - converting from non-primitive to primitive
        Integer num3 = 8;
        int num4 = num3;
        System.out.println(num4);

    }


}
