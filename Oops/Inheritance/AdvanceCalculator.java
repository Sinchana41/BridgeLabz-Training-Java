package Inheritance;

public class AdvanceCalculator  extends Calculator{
    
    public int multiply(int num1,int num2){
        return num1*num2;
    }

    public int division(int num1,int num2){
        return num1/num2;
    }

    public int moduls(int num1,int num2){
        return num1%num2;
    }
}
